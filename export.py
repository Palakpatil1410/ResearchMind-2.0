# PDF
# ---------------------------------------------------------------------------
_REPLACEMENTS = {
    "\u2013": "-",
    "\u2014": "-",
    "\u2018": "'",
    "\u2019": "'",
    "\u201c": '"',
    "\u201d": '"',
    "\u2022": "-",
    "\u2026": "...",
    "\u00b7": "-",
    "\u20b9": "Rs.",
    "\u00a0": " ",
}


def _latin(text: str) -> str:
    """Make text safe for the built-in Helvetica (latin-1) font."""
    text = str(text).replace("**", "").replace("`", "")
    for old, new in _REPLACEMENTS.items():
        text = text.replace(old, new)
    return text.encode("latin-1", "replace").decode("latin-1")


def build_pdf(topic: str, report: str) -> bytes:
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    def write(height, text):
        # Reset to the left margin and move to the next line after each cell.
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(0, height, text, new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 18)
    write(10, "ResearchMind Report")

    pdf.set_font("Helvetica", "", 11)
    write(7, _latin(f"Topic: {topic}"))
    write(7, f"Generated: {time.strftime('%B %d, %Y')}")
    pdf.ln(4)

    for line in report.splitlines():
        stripped = line.strip()
        if not stripped:
            pdf.ln(2)
            continue

        if stripped.startswith("#"):
            level = len(stripped) - len(stripped.lstrip("#"))
            text = stripped.lstrip("#").strip()
            pdf.set_font("Helvetica", "B", max(14 - level, 10))
            write(7, _latin(text))
            pdf.set_font("Helvetica", "", 10)
        elif stripped.startswith(("- ", "* ")):
            write(5, _latin("  - " + stripped[2:]))
        else:
            write(5, _latin(stripped))

    return bytes(pdf.output())
