import io
import time
from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor
from fpdf import FPDF


# ---------------------------------------------------------------------------
# DOCX
# ---------------------------------------------------------------------------
def build_docx(topic: str, report: str, feedback: str = "") -> bytes:
    doc = Document()
    for section in doc.sections:
        section.top_margin = Inches(0.8)
        section.bottom_margin = Inches(0.8)
        section.left_margin = Inches(0.9)
        section.right_margin = Inches(0.9)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("ResearchMind Report")
    run.bold = True
    run.font.size = Pt(23)
    run.font.color.rgb = RGBColor(255, 140, 50)

    sub = doc.add_paragraph(f"Topic: {topic}")
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    date = doc.add_paragraph(f"Generated: {time.strftime('%B %d, %Y')}")
    date.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for line in report.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("### "):
            doc.add_heading(line[4:], level=3)
        elif line.startswith("## "):
            doc.add_heading(line[3:], level=2)
        elif line.startswith("# "):
            doc.add_heading(line[2:], level=1)
        elif line.startswith(("- ", "* ")):
            doc.add_paragraph(line[2:], style="List Bullet")
        else:
            doc.add_paragraph(line)

    if feedback.strip():
        doc.add_page_break()
        doc.add_heading("Fact-Check Summary", level=1)
        for line in feedback.splitlines():
            if line.strip():
                doc.add_paragraph(line.strip())

    doc.add_paragraph("Generated by ResearchMind 2.0 - Multi-Agent Market Intelligence")
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


